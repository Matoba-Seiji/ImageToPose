"""Build a Maya joint hierarchy from an externally supplied pose frame.

The functions that validate and convert pose data are Maya-independent. The
scene writer replaces the previous skeleton generated by this tool, then
creates the new body joints and their parent links. Other scene nodes are not
selected, modified, bound, constrained, keyed, or deleted.
"""

from __future__ import annotations

import math


SKELETON_DATA_VERSION = "maya-pose-skeleton-v7-hands"
GENERATED_MARKER_ATTRIBUTE = "mayaPoseToolSkeleton"
GENERATED_MARKER_VALUE = "maya_pose_tool"


BODY_JOINTS = (
    "pelvis",
    "spine_1",
    "spine_2",
    "spine_3",
    "neck",
    "head",
    "left_collar",
    "left_shoulder",
    "left_elbow",
    "left_wrist",
    "right_collar",
    "right_shoulder",
    "right_elbow",
    "right_wrist",
    "left_hip",
    "left_knee",
    "left_ankle",
    "left_foot",
    "right_hip",
    "right_knee",
    "right_ankle",
    "right_foot",
)


FINGER_JOINTS = tuple(
    "{}_{}_{}".format(side, finger, segment)
    for side in ("left", "right")
    for finger in ("thumb", "index", "middle", "ring", "pinky")
    for segment in (1, 2, 3)
)


BODY_AND_FINGER_JOINTS = BODY_JOINTS + FINGER_JOINTS


BODY_PARENTS = {
    "spine_1": "pelvis",
    "spine_2": "spine_1",
    "spine_3": "spine_2",
    "neck": "spine_3",
    "head": "neck",
    "left_collar": "spine_3",
    "left_shoulder": "left_collar",
    "left_elbow": "left_shoulder",
    "left_wrist": "left_elbow",
    "right_collar": "spine_3",
    "right_shoulder": "right_collar",
    "right_elbow": "right_shoulder",
    "right_wrist": "right_elbow",
    "left_hip": "pelvis",
    "left_knee": "left_hip",
    "left_ankle": "left_knee",
    "left_foot": "left_ankle",
    "right_hip": "pelvis",
    "right_knee": "right_hip",
    "right_ankle": "right_knee",
    "right_foot": "right_ankle",
}


for _side in ("left", "right"):
    for _finger in ("thumb", "index", "middle", "ring", "pinky"):
        BODY_PARENTS["{}_{}_1".format(_side, _finger)] = "{}_wrist".format(_side)
        BODY_PARENTS["{}_{}_2".format(_side, _finger)] = "{}_{}_1".format(
            _side, _finger
        )
        BODY_PARENTS["{}_{}_3".format(_side, _finger)] = "{}_{}_2".format(
            _side, _finger
        )


BODY_ALIASES = {
    "spine_1": ("spine_1", "spine1", "spine_01"),
    "spine_2": ("spine_2", "spine2", "spine_02"),
    "spine_3": ("spine_3", "spine3", "spine_03"),
}


class PoseDataError(ValueError):
    """Raised when supplied pose data cannot describe a body skeleton."""


def _finite_number(value, label):
    try:
        number = float(value)
    except (TypeError, ValueError) as error:
        raise PoseDataError("{} must contain numbers".format(label)) from error
    if not math.isfinite(number):
        raise PoseDataError("{} must contain finite numbers".format(label))
    return number


def source_to_maya(position, coordinate_system):
    """Convert one protocol position to Maya's X/Y/Z-up world convention.

    The framework accepts root-relative Maya coordinates directly. Camera-style
    and provider-specific world frames are converted to Maya's Y-up convention
    before writing to the scene.
    """

    if not isinstance(position, (list, tuple)) or len(position) != 3:
        raise PoseDataError("joint position must be a three-number array")
    x, y, z = (_finite_number(value, "joint position") for value in position)
    if coordinate_system == "root_relative_y_up":
        return x, y, z
    if coordinate_system == "root_relative_mediapipe_world":
        # MediaPipe world landmarks use a camera-style Y-down frame.  Negating
        # Z keeps the camera-facing side consistent with Maya's convention.
        return x, -y, -z
    if coordinate_system in (
        "root_relative_camera_y_down",
        "root_relative_camera_xyz",
    ):
        return x, -y, z
    raise PoseDataError("unsupported coordinate system: {}".format(coordinate_system))


def body_joint_positions(frame, include_fingers=None):
    """Return the body positions and, when present, optional finger positions.

    Body joints are required. Finger chains are optional so a photo with only
    one visible hand can still produce the body plus that hand's complete
    fingers. Older external providers can still request the original 52-joint
    body-and-finger skeleton by supplying all finger joints.
    """

    if not isinstance(frame, dict):
        raise PoseDataError("pose response must be an object")
    joints = frame.get("joints")
    if not isinstance(joints, dict):
        raise PoseDataError("pose response has no joints object")
    coordinate_system = frame.get("coordinate_system")
    if not isinstance(coordinate_system, str):
        raise PoseDataError("pose response has no coordinate system")
    if frame.get("skeleton") != "maya_pose_skeleton":
        raise PoseDataError("pose frame is not a Maya skeleton frame")

    if include_fingers is None:
        include_fingers = frame.get("include_fingers")
    if include_fingers is None:
        include_fingers = all(name in joints for name in FINGER_JOINTS)

    joint_names = list(BODY_JOINTS)
    if include_fingers:
        for side in ("left", "right"):
            for finger in ("thumb", "index", "middle", "ring", "pinky"):
                chain = tuple(
                    "{}_{}_{}".format(side, finger, segment)
                    for segment in (1, 2, 3)
                )
                if all(name in joints for name in chain):
                    joint_names.extend(chain)
    positions = {}
    missing = []
    for name in joint_names:
        item = None
        for candidate in BODY_ALIASES.get(name, (name,)):
            if candidate in joints:
                item = joints[candidate]
                break
        if not isinstance(item, dict) or "position" not in item:
            missing.append(name)
            continue
        positions[name] = source_to_maya(item["position"], coordinate_system)

    if missing:
        raise PoseDataError("pose response is missing joints: {}".format(
            ", ".join(missing)
        ))
    return positions


def _scaled(position, scale):
    return tuple(component * scale for component in position)


def _existing_nodes(
    cmds,
    requested_prefix,
    joint_names,
    generated_marker_value=GENERATED_MARKER_VALUE,
):
    """Find the previous tool skeleton or any partial hierarchy it left."""

    existing = []

    def add_if_existing(node):
        if node and cmds.objExists(node) and node not in existing:
            existing.append(node)

    # The stable root handles skeletons created before marker attributes were
    # introduced. Checking every expected name also cleans up an interrupted
    # creation whose children were never parented under the root.
    for joint_name in joint_names:
        add_if_existing(requested_prefix + joint_name)

    # Marker lookup survives Maya module reloads and scene saves. It is limited
    # to joints created by this tool, so unrelated rigs are left untouched.
    if hasattr(cmds, "ls"):
        for node in cmds.ls(type="joint", long=True) or ():
            leaf_name = node.rsplit("|", 1)[-1]
            if leaf_name.startswith(requested_prefix):
                suffix = leaf_name[len(requested_prefix):]
                parts = suffix.split("_", 1)
                is_legacy_generated = (
                    suffix in joint_names
                    or (
                        len(parts) == 2
                        and parts[0].isdigit()
                        and parts[1] in joint_names
                    )
                )
                if is_legacy_generated:
                    add_if_existing(node)

            if not hasattr(cmds, "attributeQuery"):
                continue
            try:
                marked = cmds.attributeQuery(
                    GENERATED_MARKER_ATTRIBUTE,
                    node=node,
                    exists=True,
                )
                if marked and cmds.getAttr(
                    node + "." + GENERATED_MARKER_ATTRIBUTE
                ) == generated_marker_value:
                    add_if_existing(node)
            except Exception:
                continue
    return existing


def _delete_previous_skeleton(
    cmds,
    requested_prefix,
    joint_names,
    generated_marker_value=GENERATED_MARKER_VALUE,
):
    """Delete only the prior hierarchy owned by this tool."""

    for node in _existing_nodes(
        cmds,
        requested_prefix,
        joint_names,
        generated_marker_value=generated_marker_value,
    ):
        if not cmds.objExists(node):
            continue
        try:
            # Deleting the root removes its children as well. The existence
            # check on the next iteration skips those already-cascaded nodes.
            cmds.delete(node)
        except Exception:
            # A stale child can disappear with its parent between the check
            # and delete call; it should not block the next generation.
            continue


def _mark_generated_root(
    cmds,
    root,
    generated_marker_value=GENERATED_MARKER_VALUE,
):
    """Mark the root so a later run can replace it after a module reload."""

    if not hasattr(cmds, "addAttr") or not hasattr(cmds, "setAttr"):
        return
    try:
        if not cmds.attributeQuery(
            GENERATED_MARKER_ATTRIBUTE,
            node=root,
            exists=True,
        ):
            cmds.addAttr(
                root,
                longName=GENERATED_MARKER_ATTRIBUTE,
                dataType="string",
            )
        cmds.setAttr(
            root + "." + GENERATED_MARKER_ATTRIBUTE,
            generated_marker_value,
            type="string",
        )
    except Exception:
        # The stable root name remains a fallback for older Maya scenes.
        pass


def create_skeleton_from_pose(
    frame,
    cmds,
    scale=100.0,
    name_prefix="PoseSkeleton_",
    include_fingers=None,
    orient_joints=True,
    replace_previous=True,
    generated_marker_value=GENERATED_MARKER_VALUE,
):
    """Replace the prior generated hierarchy with a new body-and-finger rig.

    ``cmds`` is injected so the data path can be tested without Maya.  The
    source positions are root-relative, so the pelvis remains at the Maya
    origin and no scene-based offset is introduced. When Maya exposes the
    joint edit command, the new hierarchy is oriented along its bones. Set
    ``replace_previous`` to false only when multiple generated rigs are wanted.
    """

    scale = _finite_number(scale, "scale")
    if scale <= 0.0:
        raise PoseDataError("scale must be greater than zero")
    if not isinstance(name_prefix, str) or not name_prefix:
        raise PoseDataError("name prefix must be a non-empty string")

    positions = body_joint_positions(frame, include_fingers=include_fingers)
    joint_names = tuple(positions.keys())
    if not isinstance(replace_previous, bool):
        raise PoseDataError("replace_previous must be a boolean")
    if replace_previous:
        _delete_previous_skeleton(
            cmds,
            name_prefix,
            joint_names,
            generated_marker_value=generated_marker_value,
        )
    resolved_prefix = name_prefix
    created = {}
    orientation_applied = False
    try:
        # Create all pivots in world space before parenting.  Parenting with
        # absolute=True below preserves the coordinates returned by the provider.
        for joint_name in joint_names:
            created[joint_name] = cmds.createNode(
                "joint", name=resolved_prefix + joint_name
            )
            cmds.xform(
                created[joint_name],
                worldSpace=True,
                translation=_scaled(positions[joint_name], scale),
            )

        for joint_name in joint_names:
            parent_name = BODY_PARENTS.get(joint_name)
            if parent_name is not None and parent_name in created:
                cmds.parent(
                    created[joint_name],
                    created[parent_name],
                    absolute=True,
                )
    except Exception:
        # Roll back only nodes created by this call if Maya rejects a node or
        # parent operation.  A successful call never deletes scene content.
        for node in reversed(tuple(created.values())):
            try:
                if cmds.objExists(node):
                    cmds.delete(node)
            except Exception:
                pass
        raise

    _mark_generated_root(
        cmds,
        created["pelvis"],
        generated_marker_value=generated_marker_value,
    )

    if orient_joints and hasattr(cmds, "joint"):
        try:
            cmds.joint(
                created["pelvis"],
                edit=True,
                orientJoint="xyz",
                secondaryAxisOrient="yup",
                children=True,
                zeroScaleOrient=True,
            )
            orientation_applied = True
        except Exception:
            # Position and parenting are still useful if a Maya version or a
            # non-standard branch layout rejects automatic joint orientation.
            orientation_applied = False

    return {
        "success": True,
        "root": created["pelvis"],
        "joint_count": len(created),
        "joints": created,
        "name_prefix": resolved_prefix,
        "requested_name_prefix": name_prefix,
        "scale": scale,
        "coordinate_system": frame.get("coordinate_system"),
        "include_fingers": any(name in created for name in FINGER_JOINTS),
        "orientation_applied": orientation_applied,
        "scene_changes": (
            "replaced_previous_generated_skeleton"
            if replace_previous
            else "created_body_joints_only"
        ),
    }
